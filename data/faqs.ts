const ALL = FAQ_GROUPS.flatMap((g) => g.items);

/** id の順に質問を取り出す（他ページでの表示用） */
export function pickFaqs(ids: string[]): Faq[] {
  return ids.map((id) => {
    const f = ALL.find((x) => x.id === id);
    if (!f) throw new Error(`FAQ が見つかりません: ${id}`);
    return f;
  });
}
