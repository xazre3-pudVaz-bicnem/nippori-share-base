export type TermsBlock =
  | { type: "p"; text: string }
  | { type: "ul"; items: string[] }
  | { type: "ol"; items: string[] }
  /** 条の中の小見出し */
  | { type: "h"; text: string }
  /** 区切り（原文でページが変わる位置。文言は足さない） */
  | { type: "hr" };

